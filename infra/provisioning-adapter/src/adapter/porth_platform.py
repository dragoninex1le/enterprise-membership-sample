"""`porth-platform` - bootstrap (PRF-11): check the Porth install's platform baseline, and write
what is missing.

**What the baseline is.** Exactly what EMS's Porth install writes, and nothing more - the shared
`scripts/bootstrap_platform_tenant.py` and the IdP step of `porth-bootstrap.yml` after it:

1. the platform organisation and the platform tenant (`role_type = platform-admin`, PORTH-585);
2. the ten `porth-platform` permissions registered under the platform tenant;
3. the `platform-admin` system role, answering to the `platform-admin` claim value;
4. its grants of those ten permissions - and only those: a grant from any other namespace is the
   consuming app's (PORTH-609) and is never removed;
5. the platform claim mapping, its roles claim namespaced by the install's audience;
6. the platform tenant's `idp_config_override`, read back from `/porth/auth`, so the authorizer and
   the BFF proxy agree on the issuer.

`tests/test_porth_platform.py` pins every constant here to the install script's, so the two cannot
drift. Each piece is read first and written only if it is missing or differs, so a slot the install
bootstrapped answers `unchanged` throughout - and a dry run says what it would write and writes
nothing (C14).

**Not labelled for teardown.** This is the slot's baseline, not a run's fixture: teardown never
removes it and reset never touches it (C16). The handles carry the run id the contract requires,
and nothing more.
"""
from __future__ import annotations

import hashlib
import json
import os
import uuid
from datetime import datetime, timezone

import aws
import slots
from envelope import ContractError

ENTITY = "porth-platform"
APP_NS = "porth-platform"
TENANT_ID = "platform"
ROLE_NAME = "platform-admin"
AUTH_PARAMETER = "/porth/auth"

PERMISSIONS = [
    {"key": "platform.tenants.read",   "display_name": "View Tenants",           "category": "Tenants",       "sort_order": 10},
    {"key": "platform.tenants.create", "display_name": "Create Tenants",          "category": "Tenants",       "sort_order": 20},
    {"key": "platform.tenants.update", "display_name": "Update Tenants",          "category": "Tenants",       "sort_order": 30},
    {"key": "platform.tenants.delete", "display_name": "Delete Tenants",          "category": "Tenants",       "sort_order": 40},
    {"key": "platform.orgs.read",      "display_name": "View Organisations",      "category": "Organisations", "sort_order": 10},
    {"key": "platform.orgs.create",    "display_name": "Create Organisations",    "category": "Organisations", "sort_order": 20},
    {"key": "platform.orgs.update",    "display_name": "Update Organisations",    "category": "Organisations", "sort_order": 30},
    {"key": "platform.orgs.delete",    "display_name": "Delete Organisations",    "category": "Organisations", "sort_order": 40},
    {"key": "platform.settings.read",  "display_name": "View Platform Settings",  "category": "Settings",      "sort_order": 10},
    {"key": "platform.settings.write", "display_name": "Edit Platform Settings",  "category": "Settings",      "sort_order": 20},
]


def mapping_source(namespace: str) -> dict:
    return {
        "schema_version": "2.0",
        "fields": [
            {
                "name": "roles",
                "source": namespace,
                "type": "collection",
                "required": False,
                "ops": [{"op": "resolve_roles"}],
            }
        ],
        "default_roles": [],
    }


def compiled_source(namespace: str) -> str:
    """The install script's pre-generated source, byte for byte - header comment included - so a
    slot it bootstrapped hashes the same here and reads `unchanged`."""
    return (
        "# AUTO-GENERATED by claim_mapping_codegen — config hash c9845fb83254fbc8\n"
        "# DO NOT EDIT manually. Re-generate from the mapping config.\n"
        "from __future__ import annotations\n"
        "from typing import Any\n"
        "from porth_common.services.exceptions import MappingError\n"
        "\n"
        "def _get_path(obj: dict, path: str) -> Any:\n"
        '    """OIDC-aware dot-notation path resolver."""\n'
        "    if not isinstance(obj, dict) or not path:\n"
        "        return None\n"
        '    if path.startswith(("http://", "https://")):\n'
        "        return obj.get(path)\n"
        '    parts = path.split(".")\n'
        "    current: Any = obj\n"
        "    for part in parts:\n"
        "        if not isinstance(current, dict):\n"
        "            return None\n"
        "        current = current.get(part)\n"
        "        if current is None:\n"
        "            return None\n"
        "    return current\n"
        "\n"
        "def map_claims(claims: dict, role_registry: dict | None = None) -> dict:\n"
        '    """Map JWT claims to user model fields.\n'
        "    \n"
        "    Args:\n"
        "        claims: Raw JWT claims dict from identity provider.\n"
        "        role_registry: Optional dict mapping source_key values to role IDs.\n"
        "            Required for fields with resolve_roles op.\n"
        "    Returns:\n"
        "        Dict of {field_name: transformed_value}.\n"
        "    Raises:\n"
        "        MappingError: If a required claim is absent.\n"
        '    """\n'
        "    result: dict = {}\n"
        "\n"
        "    # field: roles (collection)\n"
        f"    _v = claims.get('{namespace}')\n"
        "    if _v is not None:\n"
        "        if not isinstance(_v, list):\n"
        "            _v = [_v]\n"
        "        _collection = []\n"
        "        for _elem in _v:\n"
        "            _ev = _elem\n"
        "            # resolve_roles: match against role registry\n"
        "            if _ev is not None and role_registry is not None:\n"
        "                _ev = role_registry.get(str(_ev))\n"
        "            if _ev is not None:\n"
        "                _collection.append(_ev)\n"
        "        result['roles'] = list(dict.fromkeys(_collection))\n"
        "\n"
        "    return result\n"
    )


def compiled_hash(namespace: str) -> str:
    return hashlib.sha256(compiled_source(namespace).encode()).hexdigest()


def _auth() -> dict:
    """The install's own record of its IdP - the blob the proxy reads."""
    try:
        raw = aws.client("ssm").get_parameter(Name=AUTH_PARAMETER)["Parameter"]["Value"]
        blob = json.loads(raw)
    except Exception as e:  # noqa: BLE001 - without it there is no baseline to compare against
        raise ContractError(
            "failed", "upstream_error",
            f"could not read {AUTH_PARAMETER} ({type(e).__name__}); porth-install builds it - run the install first",
        ) from e
    missing = [k for k in ("issuer", "jwks_uri", "audience") if not (blob.get(k) or "").strip()]
    if missing:
        raise ContractError(
            "failed", "upstream_error",
            f"{AUTH_PARAMETER} has no {', '.join(missing)}; the platform baseline cannot be derived without it",
        )
    return blob


def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _handle(kind: str, alias: str, outcome: str, run_id: str, ident: str | None = None) -> dict:
    handle = {"alias": alias, "type": kind, "entity": ENTITY, "outcome": outcome, "labels": {"run_id": run_id}}
    if ident:
        handle["id"] = ident
    return handle


def _outcome(present: int, written: int) -> str:
    """For a piece made of several rows: nothing there before is created, anything written is updated."""
    if not written:
        return "unchanged"
    return "created" if not present else "updated"


def bootstrap(env_scope: str, run_id: str, dry_run: bool, payload: object) -> tuple[list[dict], list[str]]:
    if payload not in (None, {}):
        raise ContractError("refused", "dataset_conflict",
                            "bootstrap takes no payload: the baseline is the target's to define (D7)")
    blob = _auth()
    namespace = f"{blob['audience'].strip().rstrip('/')}/roles"
    idp = {
        "issuer": blob["issuer"],
        "jwks_uri": blob["jwks_uri"],
        "client_id": blob.get("interactive_client_id", ""),
        "audience": blob.get("audience", ""),
        "protocol": blob.get("protocol", "oidc"),
    }

    res = aws.resource("dynamodb", **slots.data_credentials(env_scope))
    tenants = res.Table(os.environ["PORTH_TENANTS_TABLE"])
    perms = res.Table(os.environ["PORTH_PERMISSIONS_TABLE"])
    roles = res.Table(os.environ["PORTH_ROLES_TABLE"])
    claims = res.Table(os.environ["PORTH_CLAIM_MAPPING_CONFIGS_TABLE"])
    env = lambda base: f"ENV#{env_scope}#{base}"  # noqa: E731 - partition keys only, never sort keys
    now = _now()
    handles: list[dict] = []
    planned: list[str] = []

    def write(note: str, fn) -> None:
        planned.append(note)
        if not dry_run:
            fn()

    # 0. Platform org and tenant - bootstrap_platform_org_and_tenant, then porth-bootstrap.yml's patch.
    platform_pk = env(f"TENANT#{TENANT_ID}")
    tenant = tenants.get_item(Key={"PK": platform_pk, "SK": "METADATA"}, ConsistentRead=True).get("Item")
    if tenant is None:
        org_id = str(uuid.uuid4())
        write("the platform organisation", lambda: tenants.put_item(Item={
            "PK": env(f"ORG#{org_id}"), "SK": "METADATA",
            "gsi1pk": env("ORG_SLUG#platform"), "gsi1sk": "METADATA",
            "id": org_id, "name": "Platform", "slug": "platform",
            "status": "active", "created_at": now, "updated_at": now,
        }))
        write("the platform tenant", lambda: tenants.put_item(Item={
            "PK": platform_pk, "SK": "METADATA",
            "gsi1pk": env(f"ORG#{org_id}"), "gsi1sk": f"TENANT#{TENANT_ID}",
            "tenant_id": TENANT_ID, "org_id": org_id, "org_name": "Platform",
            "display_name": "Platform", "tenant_tier": "production",
            "role_type": "platform-admin",
            "status": "active", "created_at": now, "updated_at": now,
        }))
        handles.append(_handle("porth.org", "platform", "created", run_id, org_id))
        tenant_outcome = "created"
    else:
        org_id = tenant["org_id"]
        org = tenants.get_item(Key={"PK": env(f"ORG#{org_id}"), "SK": "METADATA"}, ConsistentRead=True).get("Item")
        if org is None:
            # The tenant names an organisation that is gone. Restore it under the id the tenant holds,
            # so the tenant row stays as it is.
            write("the platform organisation", lambda: tenants.put_item(Item={
                "PK": env(f"ORG#{org_id}"), "SK": "METADATA",
                "gsi1pk": env("ORG_SLUG#platform"), "gsi1sk": "METADATA",
                "id": org_id, "name": "Platform", "slug": "platform",
                "status": "active", "created_at": now, "updated_at": now,
            }))
        handles.append(_handle("porth.org", "platform", "created" if org is None else "unchanged", run_id, org_id))
        tenant_outcome = "unchanged"
    if tenant is None or tenant.get("idp_config_override") != idp or tenant.get("tenant_tier") != "production" \
            or tenant.get("role_type") != "platform-admin":
        write("the platform tenant's IdP config, tier and role type", lambda: tenants.update_item(
            Key={"PK": platform_pk, "SK": "METADATA"},
            UpdateExpression="SET idp_config_override = :idp, tenant_tier = :tier, role_type = :rt, updated_at = :ua",
            ExpressionAttributeValues={":idp": idp, ":tier": "production", ":rt": "platform-admin", ":ua": now},
        ))
        tenant_outcome = "created" if tenant is None else "updated"
    handles.append(_handle("tenant", TENANT_ID, tenant_outcome, run_id, TENANT_ID))

    # 1. Permissions - bootstrap_permissions. An existing row keeps its id and created_at.
    perm_pk = env(f"TENANT#{TENANT_ID}#NS#{APP_NS}")
    present = written = 0
    for p in PERMISSIONS:
        desired = {
            "pk": perm_pk, "sk": f"PERM#{p['key']}",
            "gsi1pk": env(f"TENANT#{TENANT_ID}"), "gsi1sk": f"CAT#{p['category']}#PERM#{p['key']}",
            "key": p["key"], "display_name": p["display_name"],
            "category": p["category"], "app_namespace": APP_NS,
            "tenant_id": TENANT_ID, "sort_order": p["sort_order"],
        }
        existing = perms.get_item(Key={"pk": perm_pk, "sk": desired["sk"]}, ConsistentRead=True).get("Item")
        present += existing is not None
        if existing is not None and all(existing.get(k) == v for k, v in desired.items()):
            continue
        item = {**desired, "id": (existing or {}).get("id") or str(uuid.uuid4()),
                "created_at": (existing or {}).get("created_at", now), "updated_at": now}
        write(f"permission {p['key']}", lambda item=item: perms.put_item(Item=item))
        written += 1
    handles.append(_handle("porth.permission", APP_NS, _outcome(present, written), run_id))

    # 2. The platform-admin role - bootstrap_role.
    found = roles.query(
        KeyConditionExpression="pk = :pk AND begins_with(sk, :r)",
        ExpressionAttributeValues={":pk": platform_pk, ":r": "ROLE#"},
        ConsistentRead=True,
    ).get("Items", [])
    role = next((r for r in found if r.get("name") == ROLE_NAME), None)
    if role is None:
        role_id = str(uuid.uuid4())
        write("the platform-admin role", lambda: roles.put_item(Item={
            "pk": platform_pk, "sk": f"ROLE#{role_id}",
            "id": role_id, "tenant_id": TENANT_ID, "name": ROLE_NAME,
            "is_system": True, "source_key": "platform-admin",
            "description": "System role for platform-level tenant administration",
            "created_at": now, "updated_at": now,
        }))
        role_outcome = "created"
    else:
        role_id = role["id"]
        role_outcome = "unchanged"
        if role.get("source_key") != "platform-admin":
            write("the platform-admin role's claim value", lambda: roles.update_item(
                Key={"pk": platform_pk, "sk": f"ROLE#{role_id}"},
                UpdateExpression="SET source_key = :sk, updated_at = :ua",
                ExpressionAttributeValues={":sk": "platform-admin", ":ua": now},
            ))
            role_outcome = "updated"
    handles.append(_handle("porth.role", ROLE_NAME, role_outcome, run_id, role_id))

    # 3. Its grants - bootstrap_role_permissions: only the grants it owns (PORTH-609), on the
    #    tenant-leading key (PORTH-607); the legacy key is swept, and anyone else's grant there moved.
    owned = {p["key"] for p in PERMISSIONS}
    role_pk = env(f"TENANT#{TENANT_ID}#ROLE#{role_id}")
    legacy_pk = env(f"ROLE#{role_id}")
    held: set[str] = set()
    swept = 0
    for pk in (role_pk, legacy_pk):
        rows = [] if role is None else roles.query(
            KeyConditionExpression="pk = :pk AND begins_with(sk, :p)",
            ExpressionAttributeValues={":pk": pk, ":p": "PERM#"},
            ConsistentRead=True,
        ).get("Items", [])
        for row in rows:
            key = row.get("permission_key") or row["sk"].removeprefix("PERM#")
            if pk == role_pk:
                held.add(key)
                continue
            if key in owned:
                write(f"a legacy grant of {key}", lambda row=row: roles.delete_item(Key={"pk": row["pk"], "sk": row["sk"]}))
            else:
                moved = {**row, "pk": role_pk}
                write(f"another namespace's legacy grant of {key}, moved", lambda row=row, moved=moved: (
                    roles.put_item(Item=moved), roles.delete_item(Key={"pk": row["pk"], "sk": row["sk"]})))
            swept += 1
    missing = sorted(owned - held)
    for key in missing:
        write(f"the grant of {key}", lambda key=key: roles.put_item(Item={
            "pk": role_pk, "sk": f"PERM#{key}",
            "role_id": role_id, "permission_key": key,
            "tenant_id": TENANT_ID, "assigned_at": now,
        }))
    handles.append(_handle("porth.role-grant", ROLE_NAME, _outcome(len(held & owned) + swept, len(missing) + swept), run_id))

    # 4. The claim mapping - bootstrap_claim_mapping_config: a new version only when the source changed.
    latest = claims.query(
        KeyConditionExpression="PK = :pk", ExpressionAttributeValues={":pk": platform_pk},
        ScanIndexForward=False, Limit=1, ConsistentRead=True,
    ).get("Items", [])
    digest = compiled_hash(namespace)
    if latest and latest[0].get("compiled_hash") == digest:
        claim_outcome = "unchanged"
    else:
        version = int(latest[0]["version"]) + 1 if latest else 1
        write(f"claim mapping version {version}", lambda: claims.put_item(Item={
            "PK": platform_pk, "SK": f"VERSION#{version:06d}",
            "gsi1pk": platform_pk, "gsi1sk": f"VERSION#{version:06d}",
            "id": str(uuid.uuid4()), "tenant_id": TENANT_ID, "version": version,
            "mapping_source": mapping_source(namespace), "compiled_source": compiled_source(namespace),
            "compiled_hash": digest,
            "compiled_at": now, "created_at": now, "updated_at": now,
        }))
        claim_outcome = "updated" if latest else "created"
    handles.append(_handle("porth.claim-mapping", TENANT_ID, claim_outcome, run_id))

    if not planned:
        return handles, [f"the platform baseline in {env_scope} is complete; nothing written"]
    if dry_run:
        return handles, [f"dry run: would write {'; '.join(planned)}. Nothing written"]
    return handles, [f"wrote {'; '.join(planned)}"]
